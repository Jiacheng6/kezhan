import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { collectLearningTerms, loadLearningTerms, containsLearningTerms } from './privacy-learning.mjs';
assert.ok(process.env.XXT_DATA_DIR, '请在隔离测试目录运行');
const sensitive = '私密课程样例XYZ';
const section = '私密章节样例XYZ';
const data = { courses: [{ name: sensitive, sections: [{ name: section, tasks: [{ name: '0.1.mp4' }] }] }] };
const terms = collectLearningTerms(data);
assert.ok(terms.includes(sensitive));
assert.ok(terms.includes(section));
assert.ok(!terms.includes('0.1.mp4'));
assert.equal(containsLearningTerms(`课程名：${sensitive}`, terms), true);
assert.equal(containsLearningTerms('Cookie 和令牌都为空，但存在真实章节名：' + section, terms), true, '学习信息不能靠凭据扫描替代');
assert.equal(containsLearningTerms('示例课程甲：章节选择说明', terms), false);
const root = fs.mkdtempSync(path.join(process.env.XXT_DATA_DIR, 'learning-privacy-'));
fs.mkdirSync(path.join(root, 'data/probe-out'), { recursive: true });
fs.writeFileSync(path.join(root, 'data/probe-out/task-report.json'), JSON.stringify(data));
assert.ok(loadLearningTerms(root).includes(sensitive));
fs.writeFileSync(path.join(root, '.privacy-blocklist.local.json'), JSON.stringify({ terms: ['隐私别名XYZ'] }));
assert.ok(loadLearningTerms(root).includes('隐私别名XYZ'));
fs.writeFileSync(path.join(root, 'state.json'), '{invalid');
assert.throws(() => loadLearningTerms(root), '报告无法读取时不得默默跳过');
console.log('✓ 课程、章节、别名的隐私检查与读取失败拦截通过');
