import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
fs.mkdirSync('.desktop-test',{recursive:true});
process.env.XXT_DATA_DIR=fs.mkdtempSync(path.resolve('.desktop-test/review-unit-'));
const {ensureDirs}=await import('../../src/config.mjs');ensureDirs();
const {matchReviewQuestions,withReviewLock}=await import('../../src/chaoxing/review-recovery.mjs');
const {registerKeptPage,listKeptPages}=await import('../../src/chaoxing/quizrun.mjs');
const {mutateState,loadState,updateReviewAnswer,reviewStats}=await import('../../src/state.mjs');
const options=[{letter:'A',text:'示例选项甲'},{letter:'B',text:'示例选项乙'}];
const item={id:'demo#q1',taskKey:'demo',questionIndex:1,domIndex:0,questionId:'choice-demo',qtype:'single',options,letters:['A'],autoFilled:true,status:'filled',archive:{stemTextRaw:'示例题干'}};
const live={index:2,domIndex:1,questionId:'choice-demo',qtype:'single',options,stemTextRaw:'示例题干'};
assert.equal(matchReviewQuestions([item],[{...live,questionId:'other',domIndex:0},live])[0].question.domIndex,1,'按题目标识定位，不能按旧 DOM 顺序填写');
assert.equal(matchReviewQuestions([{...item,questionId:''}],[live])[0].question.domIndex,1,'旧记录按完整题干与选项核对');
assert.throws(()=>matchReviewQuestions([item],[{...live,questionId:'changed'}]),/无法唯一对应/);
assert.throws(()=>matchReviewQuestions([item],[live,{...live,domIndex:0}]),/无法唯一对应/);
assert.throws(()=>matchReviewQuestions([item],[{...live,options:[options[1],{...options[0],text:'变更选项'}]}]),/选项已变化/);
assert.throws(()=>matchReviewQuestions([{...item,questionId:'',archive:{}}],[live]),/无法唯一对应/,'没有身份信息不得按位置猜测');
const essay={...item,qtype:'essay',questionId:'1',options:[],archive:{stemTextRaw:'简答题完整题干'}};
const essayLive={...live,qtype:'essay',questionId:'0',options:[],stemTextRaw:'简答题完整题干'};
assert.equal(matchReviewQuestions([essay],[essayLive])[0].question.domIndex,1,'简答编辑器序号不能当稳定标识');
assert.throws(()=>matchReviewQuestions([essay],[essayLive,{...essayLive,domIndex:2}]),/无法唯一对应/,'相同题干不可猜测');
mutateState(state=>{state.reviewQueue=[item];});
const url='https://mooc1.chaoxing.com/mooc-ans/knowledge/cards?courseid=demo&num=1&token='+'x'.repeat(240);
registerKeptPage('demo',{isClosed:()=>true,url:()=>url},{totalQuestions:1});
assert.equal(loadState().keptPages.demo.url,url,'定位 URL 不能截断');
assert.equal(listKeptPages()[0].closed,true);
assert.equal(listKeptPages()[0].submittable,false);
updateReviewAnswer(item.id,['B']);
assert.equal(loadState().reviewQueue[0].filled,null);
assert.equal(loadState().reviewQueue[0].autoFilled,false,'修改本地答案不代表页面已同步');
mutateState(state=>{state.reviewQueue=[{...essay,status:'filled',autoFilled:false,filled:null,requiresReview:true}];});
assert.equal(reviewStats().filled,0,'旧简答记录没有实际回填凭证时，不能统计成已填入');
updateReviewAnswer(essay.id,{textAnswer:'已保存但尚未回填的正文',filled:null});
assert.equal(loadState().reviewQueue[0].status,'pending-review');
assert.equal(reviewStats().filled,0);
updateReviewAnswer(essay.id,{textAnswer:'已验证回填的正文',filled:{verified:true}});
assert.equal(reviewStats().filled,1);
mutateState(state=>{state.keptPages={};});
assert.ok(listKeptPages().some(record=>record.key==='demo'),'旧页面记录被清理后仍有恢复入口');
let release;
const first=withReviewLock('demo',()=>new Promise(resolve=>{release=resolve;}));
await assert.rejects(()=>withReviewLock('demo',()=>{}),/正在恢复或提交/);
release();await first;await withReviewLock('demo',()=>{});
console.log('✓ 作业恢复：题目标识、旧记录匹配、错题/选项变更拦截、完整定位保留、人工修改状态和并发保护通过');
